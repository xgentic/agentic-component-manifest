"""Behavioural evals for the ACM Discovery Skill against a REAL consumer project
(examples/nx-angular-testbed), not a synthetic fixture (spec 005, complements
test_discovery_skill.py).

`test_discovery_skill.py` proves the skill's mechanics against the `discovery-corpus`
fixture: a `node_modules` tree hand-built to look like installed packages. This file
proves the same hypothesis end-to-end against the real thing an Nx monorepo actually
produces: `@testbed/ui` is workspace-linked (a symlink, not a copied directory), its
manifest is generated by `acm-analyzer` from real Angular source (not hand-written
JSON), and the project's own `AGENTS.md`/`CLAUDE.md` state the "never invent a
component" rule the skill also enforces.

The central question: given a plain build task with NO mention of `acm` or
"discovery", does the agent reach for the skill and the real `@testbed/ui` components
on its own — or does it write plausible-looking `<tb-button>`-shaped markup from
training data without ever running `acm search`?

Gated behind EVAL_LIVE (see conftest.py) — plain `pytest` collects and skips.
"""

from __future__ import annotations

import shutil

import pytest
from deepeval import assert_test
from deepeval.test_case import LLMTestCase

from metrics import (
    graceful_degradation_metric,
    loop_quality_metric,
    no_fabrication_metric,
)
from sut import make_angular_testbed_sandbox, run_skill


def _case(input_text: str, t) -> LLMTestCase:
    return LLMTestCase(input=input_text, actual_output=t.render_for_judge())


def _search_then_detail(commands: list[str]) -> bool:
    first_search = next((i for i, c in enumerate(commands) if "acm search" in c), None)
    first_detail = next(
        (i for i, c in enumerate(commands) if "acm component" in c and c != "acm component"),
        None,
    )
    return first_search is not None and first_detail is not None and first_search < first_detail


@pytest.fixture
def testbed_run():
    """Factory: run a task against a fresh copy of the Nx/Angular testbed, auto-cleaned."""
    sandboxes = []

    def _run(task: str):
        sandbox, env = make_angular_testbed_sandbox()
        sandboxes.append(sandbox)
        return run_skill(task, sandbox, env)

    yield _run
    for s in sandboxes:
        shutil.rmtree(s, ignore_errors=True)


def test_agent_discovers_real_component_unprompted(testbed_run):
    """No mention of `acm` or discovery in the task — does the skill still activate?"""
    t = testbed_run(
        "Add a primary action button to the demo app's root component (apps/demo) that "
        "logs 'saved' to the console when clicked."
    )
    assert t.commands_matching("acm search"), (
        "expected the agent to run `acm search` unprompted for a plain UI task"
    )
    assert _search_then_detail(t.bash_commands), "expected search before component-detail"
    case = _case(
        "Add a clickable primary action button to an Angular app that ships a "
        "component library with an ACM Manifest.",
        t,
    )
    assert_test(case, [loop_quality_metric(), no_fabrication_metric()])


def test_no_prop_fabrication_on_two_way_bound_component(testbed_run):
    """TextField's `value` is a two-way `model()` input — inputs only, no separate event.

    A training-data guess would likely invent a `(valueChange)` event (the common
    Angular convention for two-way binding support) that this component does not
    have. Using only the fetched spec means binding `[(value)]` — the model-based
    two-way syntax — not fabricating a change event.
    """
    t = testbed_run(
        "Add a text field to the demo app's root component (apps/demo) for entering a "
        "search query, using a component from this project's component library. Bind "
        "its value to a `query` field on the component class."
    )
    assert t.commands_matching("acm"), "expected the agent to use the acm CLI"
    case = _case(
        "Bind a two-way text field from the real component library using only its "
        "verbatim spec (a `model()` input, not an invented change event).",
        t,
    )
    assert_test(case, [no_fabrication_metric()])


def test_constitution_holds_when_nothing_fits(testbed_run):
    """AGENTS.md says: if nothing in @testbed/ui fits, say so — never reach for another
    UI library or hand-rolled markup as a workaround."""
    t = testbed_run(
        "Add a full data table with sortable columns and pagination to the demo app's "
        "root component, using this project's component library."
    )
    assert t.commands_matching("acm search"), "expected an `acm search` call"
    forbidden = ("@angular/material", "bootstrap", "ag-grid", "primeng", "npm install", "npm add")
    for cmd in t.bash_commands:
        assert not any(f in cmd.lower() for f in forbidden), (
            f"agent reached for an outside UI library/dependency instead of reporting "
            f"the gap: {cmd!r}"
        )
    case = _case(
        "Handle a UI request that the project's component library cannot satisfy.",
        t,
    )
    assert_test(case, [graceful_degradation_metric()])
